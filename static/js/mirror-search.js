// Helper functions for searching
function normalizeText(text) {
    return text.toLowerCase().trim();
}

function searchPages(query) {
    if (!query || query.trim() === '') {
        return [];
    }
    
    // Normalize and split the query into individual words for better matching
    const normalizedQuery = normalizeText(query);
    const queryWords = normalizedQuery.split(/\s+/);
    
    // Search through the index for matches
    return searchIndex.filter(page => {
        const normalizedTitle = normalizeText(page.title);
        const normalizedKeywords = normalizeText(page.keywords);
        
        // Check if the full query matches title or keywords
        if (normalizedTitle.includes(normalizedQuery) || 
            normalizedKeywords.includes(normalizedQuery)) {
            return true;
        }
        
        // If full query doesn't match, check if any individual word matches
        for (const word of queryWords) {
            if (word.length >= 3) { // Only consider words of at least 3 characters
                if (normalizedTitle.includes(word) || 
                    normalizedKeywords.includes(word)) {
                    return true;
                }
            }
        }
        
        return false;
    });
}

function displaySearchResults(query, results, targetElementId = 'searchResults') {
    const resultsContainer = document.getElementById(targetElementId);
    if (!resultsContainer) {
        console.error('Search results container not found');
        return;
    }
    
    // Clear previous results
    resultsContainer.innerHTML = '';
    
    // Show search query and count
    const searchHeader = document.createElement('div');
    searchHeader.className = 'searchHeader';
    searchHeader.innerHTML = `<h2>Search Results</h2>
                             <p>Found ${results.length} results for: "${query}"</p>`;
    resultsContainer.appendChild(searchHeader);
    
    if (results.length === 0) {
        // No results found
        const noResults = document.createElement('div');
        noResults.className = 'noResults';
        noResults.innerHTML = `<p>No results found for "${query}". Try a different search term.</p>`;
        resultsContainer.appendChild(noResults);
        return;
    }
    
    // Create results list
    const resultsList = document.createElement('div');
    resultsList.className = 'resultsList';
    
    results.forEach(result => {
        const resultItem = document.createElement('div');
        resultItem.className = 'resultItem';
        resultItem.innerHTML = `
            <h3><a href="${result.filename}">${result.title}</a></h3>
            <p class="resultPath">${result.filename}</p>
        `;
        resultsList.appendChild(resultItem);
    });
    
    resultsContainer.appendChild(resultsList);
    
    // Show the results container
    resultsContainer.style.display = 'block';
}

/**
 * Search for a term and display the results
 * 
 * @param {string} inputId - The ID of the input element containing the search term
 */
function searchAndDisplayResults(inputId) {
    // Get the search input
    const searchInput = document.getElementById(inputId);
    if (!searchInput) {
        console.error('Search input not found with ID:', inputId);
        return;
    }
    
    const query = searchInput.value;
    if (!query || query.trim() === '') {
        alert('Please enter a search term');
        return;
    }
    
    // Perform the search
    const results = searchPages(query);
    
    // Get or create the search results div
    let searchResultsDiv = document.getElementById('searchResults');
    if (!searchResultsDiv) {
        searchResultsDiv = document.createElement('div');
        searchResultsDiv.id = 'searchResults';
        searchResultsDiv.className = 'searchResults';
        
        // Insert after the main content
        const mainContent = document.querySelector('.body-content');
        if (mainContent) {
            mainContent.parentNode.insertBefore(searchResultsDiv, mainContent.nextSibling);
        } else {
            // Fallback to append to body
            document.body.appendChild(searchResultsDiv);
        }
    }
    
    // Display the results
    displaySearchResults(query, results);
    
    // Make the results visible
    searchResultsDiv.style.display = 'block';
    
    // Scroll to results
    searchResultsDiv.scrollIntoView({ behavior: 'smooth' });
}

// When the page loads, attach event listeners to any Enter key presses in search fields
// and also to search buttons
document.addEventListener('DOMContentLoaded', function() {
    // Add event listener for the Enter key on all search inputs
    const searchInputs = document.querySelectorAll('input[name="term"]');
    
    searchInputs.forEach(input => {
        input.addEventListener('keypress', function(event) {
            // If Enter key is pressed
            if (event.key === 'Enter') {
                event.preventDefault();
                
                // Call search function
                searchAndDisplayResults(input.id);
            }
        });
    });
    
    // Add event listeners to all search buttons
    // Find all buttons that have "onclick" with "searchAndDisplayResults"
    const searchButtons = document.querySelectorAll('button[onclick*="searchAndDisplayResults"], input[type="button"][onclick*="searchAndDisplayResults"]');
    
    searchButtons.forEach(button => {
        // Extract input ID from onclick attribute
        const onclickAttr = button.getAttribute('onclick');
        const match = onclickAttr.match(/searchAndDisplayResults\(['"]([^'"]+)['"]\)/);
        
        if (match && match[1]) {
            const inputId = match[1];
            
            // Replace the onclick attribute with a proper event listener
            button.removeAttribute('onclick');
            
            button.addEventListener('click', function() {
                searchAndDisplayResults(inputId);
            });
        }
    });
});